bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    if (record->event.pressed) {
        // Check if LAYER_TMUX is currently active *anywhere in the layer stack*
        // layer_state_cmp(layer_state, 1UL << LAYER_TMUX) only checks if it's the *top* layer.
        // layer_state_is(layer_id) checks if it's the top layer.
        // This is a more robust way to check if it's anywhere in the stack.
        // We'll use layer_state as a bitmask to see if the TMUX bit is set.

        if ((layer_state & (1UL << LAYER_TMUX))) { // Check if LAYER_TMUX is active in the stack
            // Get the actual keycode as mapped on the currently active top layer
            // This is key: it tells you what the final keycode *would be* for the host.
            uint16_t actual_keycode_on_top_layer = keycode; // Start with the raw keycode

            // QMK's default behavior will resolve the top-most keycode.
            // We just need to know if we should *prefix* it.

            // --- IMPORTANT: Decide which keycodes to prefix ---
            // You generally DO NOT want to prefix:
            // - Layer switching keys (like MO, LT, TG)
            // - Transparent keys (KC_TRNS)
            // - Basic modifiers (KC_LCTL, KC_LSFT etc.) as they are typically held.
            // - Special keys like QK_BOOT
            // - Already prefixed keys (e.g., if you map C(KC_N) directly)

            // Let's filter some common keys you don't want to prefix
            switch (actual_keycode_on_top_layer) {
                // Exclude layer switching keycodes from being prefixed
                case MO(LAYER_TMUX):
                case MO(LAYER_SYM): // Or any other MO() keycodes on your other layers
                case LT(LAYER_SYM_EXT, KC_ESC): // Example LT()
                case QK_BOOT:
                case KC_TRNS:
                // Exclude basic modifiers if they are held (they don't trigger per-key action)
                case KC_LCTL: case KC_LSFT: case KC_LALT: case KC_LGUI:
                case KC_RCTL: case KC_RSFT: case KC_RALT: case KC_RGUI:
                // Add any other keycodes you explicitly do NOT want prefixed
                    return true; // Let QMK process these normally (no prefix)
                    break;
            }

            // --- If it's a keycode we DO want to prefix ---
            // Send Ctrl+B
            register_code(KC_LCTL);
            tap_code(KC_B);
            unregister_code(KC_LCTL);

            // Add a small delay for OS/Tmux to process Ctrl+B
            wait_ms(20);

            // Let QMK process the original keycode.
            // QMK will resolve it through its layer stack *after* we send Ctrl+B.
            return true; // We want QMK to send the original keycode to the host
        }
    }

    // Default: Let QMK process other keycodes normally
    return true;
}
